begin;

create table if not exists public.keyboard_showcase_inventory (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references public.profiles(id) on delete cascade,
  category text not null check (category in ('keycap', 'switch')),
  name text not null check (char_length(btrim(name)) between 1 and 120),
  brand text not null default '' check (char_length(brand) <= 120),
  quantity integer not null default 1 check (quantity between 0 and 10000),
  ownership_status text not null default 'owned' check (ownership_status in ('ordered', 'owned', 'sold')),
  acquired_at date,
  notes text not null default '' check (char_length(notes) <= 1000),
  is_public boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists keyboard_showcase_inventory_owner_idx on public.keyboard_showcase_inventory (profile_id, category, created_at desc);
drop trigger if exists keyboard_showcase_inventory_touch_updated_at on public.keyboard_showcase_inventory;
create trigger keyboard_showcase_inventory_touch_updated_at before update on public.keyboard_showcase_inventory for each row execute function public.touch_updated_at();

create table if not exists public.keyboard_showcase_item_inventory (
  item_id uuid not null references public.keyboard_showcase_items(id) on delete cascade,
  inventory_id uuid not null references public.keyboard_showcase_inventory(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (item_id, inventory_id)
);

create table if not exists public.keyboard_showcase_build_events (
  id bigint generated by default as identity primary key,
  item_id uuid not null references public.keyboard_showcase_items(id) on delete cascade,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  event_date date not null default ((now() at time zone 'Asia/Seoul')::date),
  title text not null check (char_length(btrim(title)) between 1 and 120),
  details text not null default '' check (char_length(details) <= 2000),
  build_snapshot jsonb not null default '{}'::jsonb check (jsonb_typeof(build_snapshot) = 'object'),
  is_public boolean not null default true,
  created_at timestamptz not null default now()
);
create index if not exists keyboard_showcase_build_events_item_idx on public.keyboard_showcase_build_events (item_id, event_date desc, id desc);

create or replace function public.create_initial_showcase_build_event()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  if new.status='published' and old.status is distinct from 'published'
     and not exists (select 1 from public.keyboard_showcase_build_events where item_id=new.id) then
    insert into public.keyboard_showcase_build_events (item_id,profile_id,event_date,title,build_snapshot)
    values (new.id,new.profile_id,(now() at time zone 'Asia/Seoul')::date,'첫 빌드 등록',new.build_info);
  end if;
  return new;
end;
$$;
drop trigger if exists keyboard_showcase_initial_build_event on public.keyboard_showcase_items;
create trigger keyboard_showcase_initial_build_event after update of status on public.keyboard_showcase_items
for each row execute function public.create_initial_showcase_build_event();

alter table public.keyboard_showcase_inventory enable row level security;
alter table public.keyboard_showcase_item_inventory enable row level security;
alter table public.keyboard_showcase_build_events enable row level security;
revoke all on public.keyboard_showcase_inventory, public.keyboard_showcase_item_inventory, public.keyboard_showcase_build_events from public, anon, authenticated;

create or replace function public.validate_showcase_build_info(p_build_info jsonb)
returns jsonb language plpgsql immutable set search_path = public
as $$
declare
  v_value jsonb := coalesce(p_build_info, '{}'::jsonb); v_key text; v_text text;
  v_allowed constant text[] := array[
    'brand','model','buildStatus','purchaseDate','receivedDate','completedDate','buildDate',
    'case','pcb','plate','switches','keycaps','stabilizers','switchMods','stabilizerMods',
    'mounting','foam','layout','weight','firmware','mods','typingFeel','soundProfile','cable','other'
  ];
begin
  if jsonb_typeof(v_value) <> 'object' then raise exception 'Build information must be an object'; end if;
  for v_key, v_text in select key, value from jsonb_each_text(v_value) loop
    if not (v_key = any(v_allowed)) then raise exception 'Unknown build field: %', v_key; end if;
    if char_length(v_text) > 240 then raise exception 'Build field is too long: %', v_key; end if;
  end loop;
  return v_value;
end;
$$;

create or replace function public.create_my_showcase_item(
  p_title text, p_description text default '', p_build_info jsonb default '{}'::jsonb,
  p_keyxif_url text default null, p_keyxif_snapshot jsonb default null
)
returns table (item_id uuid, profile_id uuid)
language plpgsql security definer set search_path = public
as $$
declare
  v_profile_id uuid := public.current_profile_id(); v_item_id uuid;
  v_title text := btrim(coalesce(p_title, '')); v_description text := btrim(coalesce(p_description, ''));
  v_keyxif_url text := nullif(btrim(coalesce(p_keyxif_url, '')), '');
begin
  if v_profile_id is null then raise exception 'Not authenticated'; end if;
  if char_length(v_title) not between 1 and 80 then raise exception '키보드 이름은 1~80자여야 합니다'; end if;
  if char_length(v_description) > 3000 then raise exception '설명은 3,000자 이하여야 합니다'; end if;
  if char_length(coalesce(v_keyxif_url, '')) > 500 then raise exception 'KeyXIF 주소가 너무 깁니다'; end if;
  if p_keyxif_snapshot is not null and pg_column_size(p_keyxif_snapshot) > 65536 then raise exception 'KeyXIF snapshot is too large'; end if;
  perform pg_advisory_xact_lock(hashtext(v_profile_id::text));
  if (select count(*) from public.keyboard_showcase_items i where i.profile_id=v_profile_id) >= 30 then raise exception '키보드는 계정당 최대 30대까지 등록할 수 있습니다'; end if;
  insert into public.keyboard_showcase_items (profile_id,title,description,build_info,keyxif_url,keyxif_snapshot)
  values (v_profile_id,v_title,v_description,public.validate_showcase_build_info(p_build_info),v_keyxif_url,p_keyxif_snapshot)
  returning id into v_item_id;
  return query select v_item_id,v_profile_id;
end;
$$;

create or replace function public.get_my_showcase_inventory()
returns setof public.keyboard_showcase_inventory language sql stable security definer set search_path = public
as $$ select i.* from public.keyboard_showcase_inventory i where i.profile_id=public.current_profile_id() order by i.category,i.created_at desc $$;

create or replace function public.save_my_showcase_inventory(
  p_id uuid, p_category text, p_name text, p_brand text default '', p_quantity integer default 1,
  p_ownership_status text default 'owned', p_acquired_at date default null, p_notes text default '', p_is_public boolean default true
)
returns uuid language plpgsql security definer set search_path = public
as $$
declare v_profile_id uuid := public.current_profile_id(); v_id uuid;
begin
  if v_profile_id is null then raise exception 'Not authenticated'; end if;
  if p_category not in ('keycap','switch') then raise exception 'Invalid inventory category'; end if;
  if char_length(btrim(coalesce(p_name,''))) not between 1 and 120 then raise exception '이름은 1~120자여야 합니다'; end if;
  if p_ownership_status not in ('ordered','owned','sold') then raise exception 'Invalid inventory status'; end if;
  if coalesce(p_quantity,0) not between 0 and 10000 then raise exception '수량을 확인해 주세요'; end if;
  if char_length(coalesce(p_brand,'')) > 120 or char_length(coalesce(p_notes,'')) > 1000 then raise exception '입력 내용이 너무 깁니다'; end if;
  if p_id is null then
    if (select count(*) from public.keyboard_showcase_inventory where profile_id=v_profile_id) >= 300 then raise exception '보유 장비는 최대 300개까지 등록할 수 있습니다'; end if;
    insert into public.keyboard_showcase_inventory (profile_id,category,name,brand,quantity,ownership_status,acquired_at,notes,is_public)
    values (v_profile_id,p_category,btrim(p_name),btrim(coalesce(p_brand,'')),p_quantity,p_ownership_status,p_acquired_at,btrim(coalesce(p_notes,'')),coalesce(p_is_public,true)) returning id into v_id;
  else
    update public.keyboard_showcase_inventory set category=p_category,name=btrim(p_name),brand=btrim(coalesce(p_brand,'')),quantity=p_quantity,
      ownership_status=p_ownership_status,acquired_at=p_acquired_at,notes=btrim(coalesce(p_notes,'')),is_public=coalesce(p_is_public,true)
    where id=p_id and profile_id=v_profile_id returning id into v_id;
    if v_id is null then raise exception 'Inventory item not found'; end if;
  end if;
  return v_id;
end;
$$;

create or replace function public.delete_my_showcase_inventory(p_id uuid)
returns void language plpgsql security definer set search_path = public
as $$ begin delete from public.keyboard_showcase_inventory where id=p_id and profile_id=public.current_profile_id(); if not found then raise exception 'Inventory item not found'; end if; end $$;

create or replace function public.get_my_showcase_item_inventory(p_item_id uuid)
returns table (inventory_id uuid) language sql stable security definer set search_path = public
as $$ select l.inventory_id from public.keyboard_showcase_item_inventory l join public.keyboard_showcase_items i on i.id=l.item_id where l.item_id=p_item_id and i.profile_id=public.current_profile_id() $$;

create or replace function public.set_my_showcase_item_inventory(p_item_id uuid,p_inventory_ids uuid[])
returns void language plpgsql security definer set search_path = public
as $$
declare v_profile_id uuid := public.current_profile_id();
begin
  if not exists (select 1 from public.keyboard_showcase_items where id=p_item_id and profile_id=v_profile_id) then raise exception 'Showcase item not found'; end if;
  delete from public.keyboard_showcase_item_inventory where item_id=p_item_id;
  insert into public.keyboard_showcase_item_inventory (item_id,inventory_id)
  select p_item_id,x.id from public.keyboard_showcase_inventory x where x.profile_id=v_profile_id and x.id=any(coalesce(p_inventory_ids,array[]::uuid[])) on conflict do nothing;
end;
$$;

create or replace function public.get_showcase_build_events(p_item_id uuid)
returns table (event_id bigint,event_date date,title text,details text,build_snapshot jsonb)
language sql stable security definer set search_path = public
as $$
  select e.id,e.event_date,e.title,e.details,e.build_snapshot from public.keyboard_showcase_build_events e
  join public.keyboard_showcase_items i on i.id=e.item_id
  where e.item_id=p_item_id and (i.status='published' or i.profile_id=public.current_profile_id()) and (e.is_public or i.profile_id=public.current_profile_id())
  order by e.event_date desc,e.id desc
$$;

create or replace function public.get_showcase_space_inventory(p_profile_id uuid)
returns table (inventory_id uuid,category text,name text,brand text,quantity integer,ownership_status text,acquired_at date,notes text,installed_on text[])
language sql stable security definer set search_path = public
as $$
  select x.id,x.category,x.name,x.brand,x.quantity,x.ownership_status,x.acquired_at,x.notes,
    coalesce(array_agg(i.title order by i.title) filter (where i.id is not null),array[]::text[])
  from public.keyboard_showcase_inventory x
  left join public.keyboard_showcase_item_inventory l on l.inventory_id=x.id
  left join public.keyboard_showcase_items i on i.id=l.item_id and i.status='published'
  where x.profile_id=p_profile_id and x.is_public
  group by x.id
  order by x.category,x.created_at desc
$$;

create or replace function public.add_my_showcase_build_event(p_item_id uuid,p_event_date date,p_title text,p_details text default '',p_is_public boolean default true)
returns bigint language plpgsql security definer set search_path = public
as $$
declare v_profile_id uuid := public.current_profile_id(); v_id bigint; v_snapshot jsonb;
begin
  select build_info into v_snapshot from public.keyboard_showcase_items where id=p_item_id and profile_id=v_profile_id;
  if v_snapshot is null then raise exception 'Showcase item not found'; end if;
  insert into public.keyboard_showcase_build_events (item_id,profile_id,event_date,title,details,build_snapshot,is_public)
  values (p_item_id,v_profile_id,coalesce(p_event_date,(now() at time zone 'Asia/Seoul')::date),btrim(p_title),btrim(coalesce(p_details,'')),v_snapshot,coalesce(p_is_public,true)) returning id into v_id;
  return v_id;
end;
$$;

insert into public.keyboard_showcase_build_events (item_id,profile_id,event_date,title,build_snapshot)
select i.id,i.profile_id,coalesce(i.published_at at time zone 'Asia/Seoul',i.created_at at time zone 'Asia/Seoul')::date,'첫 빌드 등록',i.build_info
from public.keyboard_showcase_items i where i.status='published' and not exists (select 1 from public.keyboard_showcase_build_events e where e.item_id=i.id);

