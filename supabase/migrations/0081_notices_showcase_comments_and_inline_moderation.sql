create or replace function public.get_showcase_comments(p_item_id uuid)
returns table (
  comment_id bigint,
  parent_id bigint,
  profile_id uuid,
  display_name text,
  profile_thumbnail_path text,
  profile_photo_updated_at timestamptz,
  body text,
  status text,
  is_mine boolean,
  is_admin boolean,
  report_count bigint,
  created_at timestamptz,
  updated_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select
    c.id,
    c.parent_id,
    c.profile_id,
    coalesce(nullif(p.display_name, ''), '익명'),
    pp.thumbnail_path,
    pp.updated_at,
    case
      when c.status = 'active' then c.body
      when c.status = 'hidden' then '관리자에 의해 숨겨진 댓글입니다.'
      else '삭제된 댓글입니다.'
    end,
    c.status,
    c.profile_id = public.current_profile_id(),
    public.is_admin(),
    case when public.is_admin() then (
      select count(*) from public.keyboard_showcase_comment_reports r
      where r.comment_id = c.id and r.reviewed_at is null
    ) else 0 end,
    c.created_at,
    c.updated_at
  from public.keyboard_showcase_comments c
  join public.profiles p on p.id = c.profile_id
  left join public.public_profiles pp on pp.profile_id = c.profile_id
  where c.item_id = p_item_id
    and exists (
      select 1 from public.keyboard_showcase_items i
      where i.id = p_item_id
        and (i.status = 'published' or i.profile_id = public.current_profile_id() or public.is_admin())
    )
  order by coalesce(c.parent_id, c.id), (c.parent_id is not null), c.created_at, c.id
$$;

create or replace function public.create_showcase_comment(
  p_item_id uuid,
  p_body text,
  p_parent_id bigint default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_profile_id uuid := public.current_profile_id();
  v_body text := btrim(coalesce(p_body, ''));
  v_id bigint;
begin
  if v_profile_id is null then raise exception 'Not authenticated'; end if;
  if char_length(v_body) not between 1 and 500 then raise exception '댓글은 1~500자여야 합니다'; end if;
  if not exists (select 1 from public.keyboard_showcase_items where id = p_item_id and status = 'published') then
    raise exception 'Showcase item not found';
  end if;
  if (select count(*) from public.keyboard_showcase_comments
      where profile_id = v_profile_id and created_at > now() - interval '5 minutes') >= 8 then
    raise exception '잠시 후 다시 작성해 주세요';
  end if;
  if p_parent_id is not null and not exists (
    select 1 from public.keyboard_showcase_comments
    where id = p_parent_id and item_id = p_item_id and parent_id is null and status = 'active'
  ) then
    raise exception '답글을 남길 댓글을 찾을 수 없습니다';
  end if;

  insert into public.keyboard_showcase_comments (item_id, profile_id, parent_id, body)
  values (p_item_id, v_profile_id, p_parent_id, v_body)
  returning id into v_id;
  return v_id;
end;
$$;

create or replace function public.delete_my_showcase_comment(p_comment_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.keyboard_showcase_comments
  set status = 'deleted', body = ''
  where id = p_comment_id and profile_id = public.current_profile_id() and status <> 'deleted';
  if not found then raise exception 'Comment not found'; end if;
end;
$$;

create or replace function public.report_showcase_comment(
  p_comment_id bigint,
  p_reason text,
  p_details text default ''
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_profile_id uuid := public.current_profile_id();
  v_reason text := lower(btrim(coalesce(p_reason, '')));
  v_details text := btrim(coalesce(p_details, ''));
begin
  if v_profile_id is null then raise exception 'Not authenticated'; end if;
  if v_reason not in ('inappropriate', 'spam', 'privacy', 'other') then raise exception 'Invalid report reason'; end if;
  if char_length(v_details) > 500 then raise exception '신고 내용은 500자 이하여야 합니다'; end if;
  if not exists (select 1 from public.keyboard_showcase_comments where id = p_comment_id and status = 'active') then
    raise exception 'Comment not found';
  end if;
  insert into public.keyboard_showcase_comment_reports (comment_id, profile_id, reason, details)
  values (p_comment_id, v_profile_id, v_reason, v_details)
  on conflict (comment_id, profile_id) do update
  set reason = excluded.reason, details = excluded.details, created_at = now(), reviewed_at = null, reviewed_by = null;
end;
$$;

create or replace function public.admin_moderate_showcase_comment(
  p_comment_id bigint,
  p_action text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_action text := lower(btrim(coalesce(p_action, '')));
begin
  if not public.is_admin() then raise exception 'Admin only'; end if;
  if v_action not in ('hide', 'restore', 'delete') then raise exception 'Invalid comment action'; end if;
  update public.keyboard_showcase_comments
  set status = case v_action when 'hide' then 'hidden' when 'restore' then 'active' else 'deleted' end,
      body = case when v_action = 'delete' then '' else body end
  where id = p_comment_id;
  if not found then raise exception 'Comment not found'; end if;
  update public.keyboard_showcase_comment_reports
  set reviewed_at = now(), reviewed_by = public.current_profile_id()
  where comment_id = p_comment_id and reviewed_at is null;
end;
$$;

create or replace function public.admin_delete_showcase_item(p_item_id uuid)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_item public.keyboard_showcase_items;
begin
  if not public.is_admin() then raise exception 'Admin only'; end if;
  select * into v_item from public.keyboard_showcase_items where id = p_item_id for update;
  if not found then raise exception 'Showcase item not found'; end if;
  delete from storage.objects
  where bucket_id = 'keyboard-showcase'
    and name in (v_item.image_path, v_item.thumbnail_path, v_item.audio_path);
  delete from public.keyboard_showcase_items where id = p_item_id;
end;
$$;

