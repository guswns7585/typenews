create or replace function public.get_public_notices(p_limit integer default 30)
returns table (
  notice_id bigint,
  title text,
  body text,
  category text,
  is_pinned boolean,
  is_published boolean,
  published_at timestamptz,
  updated_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select n.id, n.title, n.body, n.category, n.is_pinned, n.is_published,
         n.published_at, n.updated_at
  from public.site_notices n
  where n.is_published or public.is_admin()
  order by n.is_pinned desc, n.published_at desc, n.id desc
  limit least(greatest(coalesce(p_limit, 30), 1), 100)
$$;

create or replace function public.get_latest_notice_at()
returns timestamptz
language sql
stable
security definer
set search_path = public
as $$
  select max(greatest(n.published_at, n.updated_at))
  from public.site_notices n
  where n.is_published
$$;

create or replace function public.admin_save_notice(
  p_notice_id bigint,
  p_title text,
  p_body text,
  p_category text default 'update',
  p_is_pinned boolean default false,
  p_is_published boolean default true
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id bigint;
  v_title text := btrim(coalesce(p_title, ''));
  v_body text := btrim(coalesce(p_body, ''));
  v_category text := lower(btrim(coalesce(p_category, 'update')));
begin
  if not public.is_admin() then raise exception 'Admin only'; end if;
  if char_length(v_title) not between 1 and 120 then raise exception '제목은 1~120자여야 합니다'; end if;
  if char_length(v_body) not between 1 and 5000 then raise exception '내용은 1~5,000자여야 합니다'; end if;
  if v_category not in ('update', 'event', 'maintenance') then raise exception 'Invalid notice category'; end if;

  if p_notice_id is null then
    insert into public.site_notices (title, body, category, is_pinned, is_published, created_by)
    values (v_title, v_body, v_category, coalesce(p_is_pinned, false), coalesce(p_is_published, true), public.current_profile_id())
    returning id into v_id;
  else
    update public.site_notices
    set title = v_title,
        body = v_body,
        category = v_category,
        is_pinned = coalesce(p_is_pinned, false),
        is_published = coalesce(p_is_published, true),
        published_at = case when not is_published and coalesce(p_is_published, true) then now() else published_at end
    where id = p_notice_id
    returning id into v_id;
    if v_id is null then raise exception 'Notice not found'; end if;
  end if;
  return v_id;
end;
$$;

