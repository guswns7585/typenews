-- 부정행위(매크로/어뷰징) 탐지 구조.
--
-- 설계 원칙
--   1. 원시 이벤트(문장별 로그, 키로그)를 적재하지 않는다.
--      행 수가 "완료한 문장 수"에 비례하면 데이터가 무한히 늘어난다.
--   2. 클라이언트는 세션 단위 누적 집계만 올리고, 서버가 그 한 행을 덮어쓴다.
--      행 수는 "세션 수"에만 비례하고, 재전송해도 중복이 생기지 않는다.
--   3. 판정은 서버에서 한다. 룰에 걸린 경우에만 abuse_signals에 남는다.
--      같은 세션에서 같은 룰이 반복되면 새 행이 아니라 카운터만 올린다.
--   4. 클라이언트 집계는 조작될 수 있으므로, 서버 시각으로만 만들어지는
--      typing_results.created_at 간격도 함께 본다. (evaluate_server_side_signals)

-- Firestore에서 넘어온 기존 테이블은 참고용으로만 남긴다. 새 기록은 쓰지 않는다.
comment on table public.suspicious_records is
  'LEGACY: Firestore suspiciousRecords 이관 데이터. 신규 탐지는 abuse_signals를 쓴다. 이관 검증이 끝나면 삭제 가능.';

create table if not exists public.typing_sessions (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  -- 클라이언트가 만든 세션 식별자. 탭 하나가 살아 있는 동안 유지된다.
  session_key uuid not null,
  started_at timestamptz not null,
  last_seen_at timestamptz not null default now(),

  sentence_count integer not null default 0 check (sentence_count >= 0),
  typed_chars bigint not null default 0 check (typed_chars >= 0),
  -- 실제로 타이핑한 시간의 합. 창을 켜두기만 한 시간은 빠진다.
  active_ms bigint not null default 0 check (active_ms >= 0),

  -- 평균과 표준편차를 서버에서 뽑기 위한 누적값. 개별 기록은 남기지 않는다.
  cpm_sum bigint not null default 0 check (cpm_sum >= 0),
  cpm_sq_sum numeric not null default 0 check (cpm_sq_sum >= 0),
  cpm_max integer not null default 0 check (cpm_max >= 0),
  accuracy_sum bigint not null default 0 check (accuracy_sum >= 0),

  backspace_count integer not null default 0 check (backspace_count >= 0),
  paste_attempts integer not null default 0 check (paste_attempts >= 0),
  -- 창이 포커스를 잃은 상태에서 입력이 들어온 횟수.
  blurred_input_count integer not null default 0 check (blurred_input_count >= 0),

  -- 한글 문장 중 IME 조합 이벤트가 한 번이라도 있었던 문장 수.
  -- 사람이 한글을 치면 반드시 조합이 일어난다. 값이 0에 가까우면 주입 입력이다.
  hangul_sentence_count integer not null default 0 check (hangul_sentence_count >= 0),
  composed_sentence_count integer not null default 0 check (composed_sentence_count >= 0),

  -- 키 간격(ms) 분포. 사람은 편차가 크고 매크로는 균일하다.
  keystroke_count integer not null default 0 check (keystroke_count >= 0),
  interval_sum bigint not null default 0 check (interval_sum >= 0),
  interval_sq_sum numeric not null default 0 check (interval_sq_sum >= 0),

  user_agent text,
  created_at timestamptz not null default now(),
  unique (profile_id, session_key)
);

comment on table public.typing_sessions is
  '세션당 한 행만 유지되는 타이핑 행동 집계. 문장별 원시 로그는 저장하지 않는다.';

create table if not exists public.abuse_signals (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  session_id bigint references public.typing_sessions(id) on delete cascade,
  rule_code text not null,
  -- 1 관찰 / 2 의심 / 3 강한 의심
  severity smallint not null check (severity between 1 and 3),
  occurrence_count integer not null default 1 check (occurrence_count > 0),
  -- 판정 근거가 된 수치만 담는다. 문장 본문은 절대 담지 않는다.
  evidence jsonb not null default '{}'::jsonb,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  -- 관리자가 확인 처리하면 워치리스트에서 내려간다.
  reviewed_at timestamptz,
  reviewed_by uuid references public.profiles(id) on delete set null,
  review_note text,
  unique (profile_id, session_id, rule_code)
);

comment on table public.abuse_signals is
  '룰에 걸린 경우에만 생기는 탐지 신호. 같은 세션의 같은 룰은 카운터만 올린다.';

create index if not exists typing_sessions_profile_seen_idx
  on public.typing_sessions (profile_id, last_seen_at desc);
create index if not exists typing_sessions_last_seen_idx
  on public.typing_sessions (last_seen_at);
create index if not exists abuse_signals_open_idx
  on public.abuse_signals (last_seen_at desc) where reviewed_at is null;
create index if not exists abuse_signals_profile_idx
  on public.abuse_signals (profile_id, last_seen_at desc);

-- 세션과 무관한 신호(서버 시각 기반)는 session_id가 null이다.
-- NULL은 UNIQUE 제약에서 서로 다른 값으로 취급되므로 부분 인덱스로 따로 막는다.
create unique index if not exists abuse_signals_profile_rule_no_session_idx
  on public.abuse_signals (profile_id, rule_code) where session_id is null;

