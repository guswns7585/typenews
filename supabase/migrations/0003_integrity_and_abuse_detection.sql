create or replace function public.get_abuse_watchlist(
  p_since_days integer default 30,
  p_limit integer default 50
)
returns table (
  profile_id uuid,
  display_name text,
  email text,
  risk_score integer,
  max_severity smallint,
  signal_count integer,
  rule_codes text[],
  last_seen_at timestamptz,
  monthly_typing_count integer
)
language sql
stable
security definer
set search_path = public
as $$
  select
    p.id,
    coalesce(nullif(p.display_name, ''), '익명'),
    p.email::text,
    -- 심각도가 높을수록 가중치를 크게. 반복 횟수는 로그로 눌러서 한 세션이 순위를 독식하지 않게.
    sum(a.severity * a.severity * (1 + ln(a.occurrence_count)))::integer,
    max(a.severity),
    count(*)::integer,
    array_agg(distinct a.rule_code order by a.rule_code),
    max(a.last_seen_at),
    coalesce(max(ms.typing_count), 0)
  from public.abuse_signals a
  join public.profiles p on p.id = a.profile_id
  left join public.monthly_stats ms
    on ms.profile_id = p.id
   and ms.month_id = to_char(now() at time zone 'Asia/Seoul', 'YYYYMM')
  where a.reviewed_at is null
    and a.last_seen_at > now() - make_interval(days => greatest(coalesce(p_since_days, 30), 1))
    and public.is_admin()
  group by p.id, p.display_name, p.email
  order by 4 desc, 8 desc
  limit least(greatest(coalesce(p_limit, 50), 1), 500)
$$;

create or replace function public.review_abuse_signals(
  p_profile_id uuid,
  p_note text default null
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_reviewer uuid;
  v_updated integer;
begin
  if not public.is_admin() then
    raise exception 'Admin only';
  end if;

  select public.current_profile_id() into v_reviewer;

  update public.abuse_signals
  set reviewed_at = now(), reviewed_by = v_reviewer, review_note = p_note
  where profile_id = p_profile_id and reviewed_at is null;

  get diagnostics v_updated = row_count;
  return v_updated;
end;
$$;

