-- 오래된 집계를 지운다. pg_cron으로 하루 한 번 돌리는 것을 권장한다.
--   select cron.schedule('prune-integrity', '20 4 * * *', $$select public.prune_integrity_data()$$);
create or replace function public.prune_integrity_data(
  p_session_days integer default 120,
  p_reviewed_signal_days integer default 400
)
returns table (deleted_sessions integer, deleted_signals integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_sessions integer;
  v_signals integer;
begin
  -- 신호가 붙지 않은 평범한 세션만 지운다. 근거가 남아 있어야 할 세션은 보존.
  delete from public.typing_sessions ts
  where ts.last_seen_at < now() - make_interval(days => greatest(p_session_days, 7))
    and not exists (select 1 from public.abuse_signals a where a.session_id = ts.id);
  get diagnostics v_sessions = row_count;

  delete from public.abuse_signals
  where reviewed_at is not null
    and reviewed_at < now() - make_interval(days => greatest(p_reviewed_signal_days, 30));
  get diagnostics v_signals = row_count;

  return query select v_sessions, v_signals;
end;
$$;

-- ---------------------------------------------------------------------------
-- RLS / 권한
-- ---------------------------------------------------------------------------

alter table public.typing_sessions enable row level security;
alter table public.abuse_signals enable row level security;

-- 탐지 결과는 본인도 볼 수 없다. 어떤 룰에 걸렸는지 알면 회피가 쉬워진다.
drop policy if exists "typing_sessions_admin_select" on public.typing_sessions;
create policy "typing_sessions_admin_select"
on public.typing_sessions for select
to authenticated
using (public.is_admin());

drop policy if exists "abuse_signals_admin_select" on public.abuse_signals;
create policy "abuse_signals_admin_select"
on public.abuse_signals for select
to authenticated
using (public.is_admin());

revoke all on public.typing_sessions from anon, authenticated;
revoke all on public.abuse_signals from anon, authenticated;
grant select on public.typing_sessions to authenticated;
grant select on public.abuse_signals to authenticated;

-- 내부 함수는 클라이언트에 노출하지 않는다.
revoke all on function public.raise_abuse_signal(uuid, bigint, text, smallint, jsonb) from public, anon, authenticated;
revoke all on function public.evaluate_session_signals(bigint) from public, anon, authenticated;
revoke all on function public.evaluate_server_side_signals(uuid) from public, anon, authenticated;
revoke all on function public.prune_integrity_data(integer, integer) from public, anon, authenticated;

grant execute on function public.is_admin() to authenticated;
grant execute on function public.report_typing_session(uuid, timestamptz, jsonb) to authenticated;
grant execute on function public.get_abuse_watchlist(integer, integer) to authenticated;
grant execute on function public.review_abuse_signals(uuid, text) to authenticated;

notify pgrst, 'reload schema';
