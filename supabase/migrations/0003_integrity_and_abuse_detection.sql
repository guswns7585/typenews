create or replace function public.raise_abuse_signal(
  p_profile_id uuid,
  p_session_id bigint,
  p_rule_code text,
  p_severity smallint,
  p_evidence jsonb
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_updated integer;
begin
  -- session_id가 null일 수 있어서 on conflict 대신 직접 upsert 한다.
  -- `is not distinct from`이라야 null끼리도 같은 행으로 본다.
  update public.abuse_signals
  set
    occurrence_count = occurrence_count + 1,
    severity = p_severity,
    evidence = coalesce(p_evidence, '{}'::jsonb),
    last_seen_at = now(),
    -- 관리자가 확인 처리한 건은 일주일간 다시 올라오지 않는다.
    reviewed_at = case when reviewed_at < now() - interval '7 days' then null else reviewed_at end
  where profile_id = p_profile_id
    and rule_code = p_rule_code
    and session_id is not distinct from p_session_id;

  get diagnostics v_updated = row_count;
  if v_updated > 0 then
    return;
  end if;

  insert into public.abuse_signals (profile_id, session_id, rule_code, severity, evidence)
  values (p_profile_id, p_session_id, p_rule_code, p_severity, coalesce(p_evidence, '{}'::jsonb));
exception
  when unique_violation then
    -- 같은 순간에 다른 탭이 먼저 넣은 경우. 카운터만 올리고 끝낸다.
    update public.abuse_signals
    set occurrence_count = occurrence_count + 1, last_seen_at = now()
    where profile_id = p_profile_id
      and rule_code = p_rule_code
      and session_id is not distinct from p_session_id;
end;
$$;

-- ---------------------------------------------------------------------------
-- 룰 평가 (클라이언트 집계 기반)
-- ---------------------------------------------------------------------------

create or replace function public.evaluate_session_signals(p_session_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  s public.typing_sessions;
  v_avg_cpm numeric;
  v_cpm_stddev numeric;
  v_avg_accuracy numeric;
  v_avg_interval numeric;
  v_interval_stddev numeric;
  -- 변동계수. 평균 대비 흔들림의 정도라 타속이 빠르든 느리든 비교가 된다.
  v_interval_cv numeric;
  v_composition_ratio numeric;
  v_session_ms numeric;
begin
  select * into s from public.typing_sessions where id = p_session_id;
  if not found or s.sentence_count = 0 then
    return;
  end if;

  v_avg_cpm := s.cpm_sum::numeric / s.sentence_count;
  v_avg_accuracy := s.accuracy_sum::numeric / s.sentence_count;
  v_cpm_stddev := sqrt(greatest(s.cpm_sq_sum / s.sentence_count - v_avg_cpm ^ 2, 0));
  v_session_ms := extract(epoch from (s.last_seen_at - s.started_at)) * 1000;

  if s.keystroke_count >= 2 then
    v_avg_interval := s.interval_sum::numeric / s.keystroke_count;
    v_interval_stddev := sqrt(greatest(s.interval_sq_sum / s.keystroke_count - v_avg_interval ^ 2, 0));
    v_interval_cv := case when v_avg_interval > 0 then v_interval_stddev / v_avg_interval end;
  end if;

  if s.hangul_sentence_count > 0 then
    v_composition_ratio := s.composed_sentence_count::numeric / s.hangul_sentence_count;
  end if;

  -- 한글을 쳤는데 IME 조합이 거의 없었다. 사람 손으로는 나올 수 없는 패턴이다.
  if s.hangul_sentence_count >= 5 and v_composition_ratio < 0.2 then
    perform public.raise_abuse_signal(
      s.profile_id, s.id, 'NO_IME_COMPOSITION', 3,
      jsonb_build_object(
        'hangul_sentences', s.hangul_sentence_count,
        'composed_sentences', s.composed_sentence_count,
        'ratio', round(v_composition_ratio, 3)
      )
    );
  end if;

  -- 문장은 계속 완료되는데 실제 키 이벤트가 거의 없다. 값이 직접 주입되고 있다.
  if s.sentence_count >= 10 and s.keystroke_count < s.typed_chars / 4 then
    perform public.raise_abuse_signal(
      s.profile_id, s.id, 'NO_KEY_EVENTS', 3,
      jsonb_build_object(
        'sentences', s.sentence_count,
        'keystrokes', s.keystroke_count,
        'typed_chars', s.typed_chars
      )
    );
  end if;

  -- 창이 백그라운드인데 입력이 들어왔다.
  if s.blurred_input_count >= 10 then
    perform public.raise_abuse_signal(
      s.profile_id, s.id, 'BACKGROUND_INPUT', 3,
      jsonb_build_object('blurred_inputs', s.blurred_input_count)
    );
  end if;

  -- 키 간격이 지나치게 균일하다.
  if s.keystroke_count >= 200 and v_interval_cv is not null and v_interval_cv < 0.15 then
    perform public.raise_abuse_signal(
      s.profile_id, s.id, 'UNIFORM_KEY_RHYTHM', 3,
      jsonb_build_object(
        'keystrokes', s.keystroke_count,
        'avg_interval_ms', round(v_avg_interval, 1),
        'interval_cv', round(v_interval_cv, 3)
      )
    );
  end if;

  -- 한 번도 고쳐 치지 않고 거의 완벽하다.
  if s.sentence_count >= 20 and s.backspace_count = 0 and v_avg_accuracy >= 99 then
    perform public.raise_abuse_signal(
      s.profile_id, s.id, 'NO_CORRECTION', 2,
      jsonb_build_object('sentences', s.sentence_count, 'avg_accuracy', round(v_avg_accuracy, 1))
    );
  end if;

  -- 순간 최고 속도가 사람 범위를 벗어난다.
  if s.cpm_max > 1200 and v_avg_accuracy >= 98 then
    perform public.raise_abuse_signal(
      s.profile_id, s.id, 'SPEED_SPIKE', 2,
      jsonb_build_object('max_cpm', s.cpm_max, 'avg_accuracy', round(v_avg_accuracy, 1))
    );
  end if;

  -- 문장이 바뀌어도 속도가 거의 변하지 않는다. (원본 타입뉴스의 표준편차 룰)
  if s.sentence_count >= 5 and v_cpm_stddev < 50 and v_avg_accuracy >= 95 then
    perform public.raise_abuse_signal(
      s.profile_id, s.id, 'FLAT_CPM_VARIANCE', 2,
      jsonb_build_object(
        'sentences', s.sentence_count,
        'avg_cpm', round(v_avg_cpm, 1),
        'cpm_stddev', round(v_cpm_stddev, 1)
      )
    );
  end if;

  -- 붙여넣기를 계속 시도한다.
  if s.paste_attempts >= 5 then
    perform public.raise_abuse_signal(
      s.profile_id, s.id, 'PASTE_ATTEMPT', 1,
      jsonb_build_object('attempts', s.paste_attempts)
    );
  end if;

  -- 쉬지 않고 5시간 넘게 고정확도를 유지한다.
  if v_session_ms >= 5 * 60 * 60 * 1000 and v_avg_accuracy >= 95 then
    perform public.raise_abuse_signal(
      s.profile_id, s.id, 'MARATHON_SESSION', 1,
      jsonb_build_object(
        'session_hours', round(v_session_ms / 3600000, 1),
        'avg_accuracy', round(v_avg_accuracy, 1)
      )
    );
  end if;
end;
$$;

-- ---------------------------------------------------------------------------
-- 룰 평가 (서버 시각 기반. 클라이언트가 조작할 수 없는 신호)
-- ---------------------------------------------------------------------------

create or replace function public.evaluate_server_side_signals(p_profile_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
  v_avg_gap numeric;
  v_stddev_gap numeric;
  v_cv numeric;
begin
  -- 점수가 적립된 시각의 간격만 본다. created_at은 서버가 찍으므로 위조가 안 된다.
  with recent as (
    select created_at
    from public.typing_results
    where profile_id = p_profile_id
      and created_at > now() - interval '2 hours'
    order by created_at desc
    limit 120
  ),
  gaps as (
    select extract(epoch from (created_at - lag(created_at) over (order by created_at))) as gap
    from recent
  )
  select count(*), avg(gap), stddev_pop(gap)
  into v_count, v_avg_gap, v_stddev_gap
  from gaps
  where gap is not null and gap between 0.05 and 600;

  if v_count < 30 or v_avg_gap is null or v_avg_gap <= 0 then
    return;
  end if;

  v_cv := v_stddev_gap / v_avg_gap;

  -- 문장 길이가 제각각인데 제출 간격이 일정하다면 사람 손이 아니다.
  if v_cv < 0.12 then
    perform public.raise_abuse_signal(
      p_profile_id, null, 'UNIFORM_SUBMIT_INTERVAL', 3,
      jsonb_build_object(
        'samples', v_count,
        'avg_gap_sec', round(v_avg_gap, 2),
        'gap_cv', round(v_cv, 3)
      )
    );
  end if;
end;
$$;

