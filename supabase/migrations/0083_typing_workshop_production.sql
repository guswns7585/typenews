create or replace function public.ensure_typing_workshop(p_profile_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.typing_workshop_progress(profile_id)
  values (p_profile_id)
  on conflict (profile_id) do nothing;

  insert into public.typing_workshop_stations(profile_id, station)
  values (p_profile_id, 'typeset'), (p_profile_id, 'proof'), (p_profile_id, 'press')
  on conflict (profile_id, station) do nothing;
end;
$$;

create or replace function public.settle_typing_workshop(p_profile_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_progress public.typing_workshop_progress;
  v_elapsed numeric;
  v_typeset_level integer := 1;
  v_proof_level integer := 1;
  v_press_level integer := 1;
  v_typeset_total numeric;
  v_press_total numeric;
  v_new_plates bigint;
  v_new_editions bigint;
begin
  perform public.ensure_typing_workshop(p_profile_id);

  select * into v_progress
  from public.typing_workshop_progress
  where profile_id = p_profile_id
  for update;

  v_elapsed := greatest(0, least(extract(epoch from (now() - v_progress.last_processed_at)), 28800));
  if v_elapsed <= 0 then return; end if;

  select level into v_typeset_level from public.typing_workshop_stations where profile_id = p_profile_id and station = 'typeset';
  select level into v_proof_level from public.typing_workshop_stations where profile_id = p_profile_id and station = 'proof';
  select level into v_press_level from public.typing_workshop_stations where profile_id = p_profile_id and station = 'press';

  v_typeset_total := v_progress.typeset_progress + v_elapsed * (8 + v_typeset_level * 4) / 3600;
  v_new_plates := least(v_progress.manuscripts, floor(v_typeset_total)::bigint);

  v_press_total := v_progress.press_progress + v_elapsed * (5 + v_press_level * 3) / 3600;
  v_new_editions := least(v_progress.plates + v_new_plates, floor(v_press_total)::bigint);

  update public.typing_workshop_progress
  set manuscripts = manuscripts - v_new_plates,
      plates = plates + v_new_plates - v_new_editions,
      editions = editions + v_new_editions,
      quality = least(99, greatest(quality, 70 + v_proof_level * 3)),
      typeset_progress = case when v_new_plates < floor(v_typeset_total)::bigint then 0 else v_typeset_total - floor(v_typeset_total) end,
      press_progress = case when v_new_editions < floor(v_press_total)::bigint then 0 else v_press_total - floor(v_press_total) end,
      last_processed_at = now(),
      updated_at = now()
  where profile_id = p_profile_id;
end;
$$;

create or replace function public.get_my_typing_workshop_state()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_profile_id uuid := public.current_profile_id();
  v_progress public.typing_workshop_progress;
begin
  if v_profile_id is null then raise exception 'Not authenticated'; end if;
  perform public.settle_typing_workshop(v_profile_id);
  select * into v_progress from public.typing_workshop_progress where profile_id = v_profile_id;

  return jsonb_build_object(
    'progress', jsonb_build_object(
      'manuscripts', v_progress.manuscripts,
      'plates', v_progress.plates,
      'editions', v_progress.editions,
      'coins', v_progress.coins,
      'reputation', v_progress.reputation,
      'regionTier', v_progress.region_tier,
      'quality', v_progress.quality,
      'lastProcessedAt', v_progress.last_processed_at
    ),
    'stations', coalesce((
      select jsonb_object_agg(station, level)
      from public.typing_workshop_stations
      where profile_id = v_profile_id
    ), '{}'::jsonb),
    'activeContract', (
      select jsonb_build_object(
        'id', catalog.id,
        'nameKo', catalog.name_ko,
        'nameEn', catalog.name_en,
        'descriptionKo', catalog.description_ko,
        'descriptionEn', catalog.description_en,
        'targetCopies', catalog.target_copies,
        'minQuality', catalog.min_quality,
        'rewardCoins', catalog.reward_coins,
        'rewardReputation', catalog.reward_reputation,
        'delivered', active.delivered,
        'completedAt', active.completed_at
      )
      from public.typing_workshop_active_contracts active
      join public.typing_workshop_contract_catalog catalog on catalog.id = active.contract_id
      where active.profile_id = v_profile_id
    ),
    'offers', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', offer.id,
        'nameKo', offer.name_ko,
        'nameEn', offer.name_en,
        'descriptionKo', offer.description_ko,
        'descriptionEn', offer.description_en,
        'targetCopies', offer.target_copies,
        'minQuality', offer.min_quality,
        'rewardCoins', offer.reward_coins,
        'rewardReputation', offer.reward_reputation
      ) order by offer.sort_order)
      from (
        select * from public.typing_workshop_contract_catalog
        where enabled and region_tier <= v_progress.region_tier
        order by sort_order
        limit 3
      ) offer
    ), '[]'::jsonb)
  );
end;
$$;

create or replace function public.select_typing_workshop_contract(p_contract_id text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_profile_id uuid := public.current_profile_id();
  v_region_tier integer;
begin
  if v_profile_id is null then raise exception 'Not authenticated'; end if;
  perform public.settle_typing_workshop(v_profile_id);
  select region_tier into v_region_tier from public.typing_workshop_progress where profile_id = v_profile_id;

  if not exists (
    select 1 from public.typing_workshop_contract_catalog
    where id = p_contract_id and enabled and region_tier <= v_region_tier
  ) then raise exception 'Contract is unavailable'; end if;

  if exists (
    select 1 from public.typing_workshop_active_contracts
    where profile_id = v_profile_id and completed_at is null
  ) then raise exception 'Finish the active contract first'; end if;

  insert into public.typing_workshop_active_contracts(profile_id, contract_id, delivered, started_at, completed_at, updated_at)
  values (v_profile_id, p_contract_id, 0, now(), null, now())
  on conflict (profile_id) do update
  set contract_id = excluded.contract_id,
      delivered = 0,
      started_at = now(),
      completed_at = null,
      updated_at = now();

  return public.get_my_typing_workshop_state();
end;
$$;

create or replace function public.deliver_typing_workshop_editions()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_profile_id uuid := public.current_profile_id();
  v_progress public.typing_workshop_progress;
  v_active public.typing_workshop_active_contracts;
  v_contract public.typing_workshop_contract_catalog;
  v_amount integer;
  v_completed boolean := false;
begin
  if v_profile_id is null then raise exception 'Not authenticated'; end if;
  perform public.settle_typing_workshop(v_profile_id);

  select * into v_progress from public.typing_workshop_progress where profile_id = v_profile_id for update;
  select * into v_active from public.typing_workshop_active_contracts where profile_id = v_profile_id for update;
  if v_active.profile_id is null or v_active.completed_at is not null then raise exception 'No active contract'; end if;

  select * into v_contract from public.typing_workshop_contract_catalog where id = v_active.contract_id;
  if v_progress.quality < v_contract.min_quality then raise exception 'Quality requirement not met'; end if;

  v_amount := least(v_progress.editions, v_contract.target_copies - v_active.delivered);
  if v_amount <= 0 then raise exception 'No editions available'; end if;

  update public.typing_workshop_progress
  set editions = editions - v_amount, updated_at = now()
  where profile_id = v_profile_id;

  if v_active.delivered + v_amount >= v_contract.target_copies then
    v_completed := true;
    update public.typing_workshop_active_contracts
    set delivered = v_contract.target_copies, completed_at = now(), updated_at = now()
    where profile_id = v_profile_id;

    update public.typing_workshop_progress
    set coins = coins + v_contract.reward_coins,
        reputation = reputation + v_contract.reward_reputation,
        region_tier = greatest(region_tier,
          case when reputation + v_contract.reward_reputation >= 350 then 3
               when reputation + v_contract.reward_reputation >= 120 then 2
               else 1 end),
        updated_at = now()
    where profile_id = v_profile_id;

    insert into public.typing_workshop_contract_history(
      profile_id, contract_id, delivered, final_quality, reward_coins, reward_reputation
    ) values (
      v_profile_id, v_contract.id, v_contract.target_copies, v_progress.quality,
      v_contract.reward_coins, v_contract.reward_reputation
    );
  else
    update public.typing_workshop_active_contracts
    set delivered = delivered + v_amount, updated_at = now()
    where profile_id = v_profile_id;
  end if;

  return jsonb_build_object('delivered', v_amount, 'completed', v_completed, 'state', public.get_my_typing_workshop_state());
end;
$$;

create or replace function public.upgrade_typing_workshop_station(p_station text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_profile_id uuid := public.current_profile_id();
  v_level integer;
  v_cost integer;
begin
  if v_profile_id is null then raise exception 'Not authenticated'; end if;
  if p_station not in ('typeset', 'proof', 'press') then raise exception 'Invalid station'; end if;
  perform public.settle_typing_workshop(v_profile_id);

  select level into v_level from public.typing_workshop_stations
  where profile_id = v_profile_id and station = p_station for update;
  if v_level >= 50 then raise exception 'Station is at maximum level'; end if;
  v_cost := v_level * v_level * 250;

  update public.typing_workshop_progress
  set coins = coins - v_cost, updated_at = now()
  where profile_id = v_profile_id and coins >= v_cost;
  if not found then raise exception 'Not enough coins'; end if;

  update public.typing_workshop_stations
  set level = level + 1, updated_at = now()
  where profile_id = v_profile_id and station = p_station;

  return public.get_my_typing_workshop_state();
end;
$$;

create or replace function public.award_typing_game_ink()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_bonus_bps integer := 0;
  v_dust bigint;
  v_total_dust bigint;
  v_earned bigint;
  v_manuscripts bigint;
begin
  select coalesce(sum(i.quantity * item.active_bonus_bps), 0)
  into v_bonus_bps
  from public.typing_game_inventory i
  join public.typing_game_items item on item.id = i.item_id and item.enabled
  where i.profile_id = new.profile_id;

  v_bonus_bps := least(v_bonus_bps, 5000);
  v_dust := floor(new.score::numeric * 100 * (10000 + v_bonus_bps) / 10000)::bigint;

  insert into public.typing_game_wallets (profile_id)
  values (new.profile_id)
  on conflict (profile_id) do nothing;

  select ink_dust + v_dust into v_total_dust
  from public.typing_game_wallets where profile_id = new.profile_id for update;

  v_earned := v_total_dust / 1000;
  update public.typing_game_wallets
  set ink = ink + v_earned,
      lifetime_ink = lifetime_ink + v_earned,
      ink_dust = (v_total_dust % 1000)::integer,
      updated_at = now()
  where profile_id = new.profile_id;

  perform public.settle_typing_workshop(new.profile_id);
  v_manuscripts := greatest(1, floor(new.score::numeric / 25)::bigint);
  update public.typing_workshop_progress
  set manuscripts = manuscripts + v_manuscripts,
      quality = round((quality * 4 + new.accuracy) / 5.0),
      updated_at = now()
  where profile_id = new.profile_id;

  return new;
end;
$$;

