create table if not exists public.sentences (
  id bigint generated by default as identity primary key,
  language text not null check (language in ('kor', 'eng')),
  mode text not null check (mode in ('short', 'long', 'word')),
  text text not null check (char_length(btrim(text)) between 1 and 400),
  -- 밈이 섞인 묶음에만 넣을 문장인지. 기본 묶음은 밈이 없는 쪽이다.
  is_meme boolean not null default false,
  enabled boolean not null default true,
  -- 사용자 요청에서 온 문장이면 원본을 가리킨다.
  source_request_id bigint,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists sentences_pick_idx
  on public.sentences (language, mode, enabled) where enabled;

create table if not exists public.sentence_requests (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  language text not null check (language in ('kor', 'eng')),
  mode text not null check (mode in ('short', 'long', 'word')),
  text text not null check (char_length(btrim(text)) between 1 and 400),
  status text not null default 'pending' check (status in ('pending', 'accepted', 'rejected')),
  -- 관리자가 다듬어 반영한 경우 최종 문장을 남긴다.
  reviewed_text text,
  review_note text,
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists sentence_requests_pending_idx
  on public.sentence_requests (created_at) where status = 'pending';
create index if not exists sentence_requests_profile_idx
  on public.sentence_requests (profile_id, created_at desc);

drop trigger if exists sentences_touch_updated_at on public.sentences;
create trigger sentences_touch_updated_at
before update on public.sentences
for each row execute function public.touch_updated_at();

