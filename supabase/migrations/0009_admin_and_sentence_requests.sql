create or replace function public.submit_sentence_request(
  p_language text,
  p_mode text,
  p_text text
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_profile_id uuid;
  v_text text := btrim(coalesce(p_text, ''));
  v_recent integer;
  v_id bigint;
begin
  if auth.uid() is null then
    raise exception 'Not authenticated';
  end if;

  if p_language not in ('kor', 'eng') or p_mode not in ('short', 'long', 'word') then
    raise exception '잘못된 언어 또는 모드입니다';
  end if;

  if char_length(v_text) < 2 or char_length(v_text) > 400 then
    raise exception '문장은 2~400자여야 합니다';
  end if;

  select public.current_profile_id() into v_profile_id;
  if v_profile_id is null then
    raise exception 'Profile not found';
  end if;

  -- 하루 20건으로 제한한다. 심사 큐가 한 사람으로 넘치지 않게.
  select count(*) into v_recent
  from public.sentence_requests
  where profile_id = v_profile_id and created_at > now() - interval '1 day';

  if v_recent >= 20 then
    raise exception '하루에 보낼 수 있는 요청을 모두 사용했습니다';
  end if;

  insert into public.sentence_requests (profile_id, language, mode, text)
  values (v_profile_id, p_language, p_mode, v_text)
  returning id into v_id;

  return v_id;
end;
$$;

-- ---------------------------------------------------------------------------
-- 관리자용 함수
-- ---------------------------------------------------------------------------

create or replace function public.review_sentence_request(
  p_request_id bigint,
  p_accept boolean,
  p_text text default null,
  p_note text default null,
  p_is_meme boolean default false
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin uuid;
  v_request public.sentence_requests;
  v_final text;
  v_sentence_id bigint;
begin
  if not public.is_admin() then
    raise exception 'Admin only';
  end if;

  select public.current_profile_id() into v_admin;

  select * into v_request from public.sentence_requests where id = p_request_id;
  if not found then
    raise exception '요청을 찾을 수 없습니다';
  end if;
  if v_request.status <> 'pending' then
    raise exception '이미 처리된 요청입니다';
  end if;

  -- 다듬어서 반영할 수 있다. 넘기지 않으면 원문 그대로.
  v_final := btrim(coalesce(p_text, v_request.text));

  update public.sentence_requests
  set
    status = case when p_accept then 'accepted' else 'rejected' end,
    reviewed_text = case when p_accept then v_final else null end,
    review_note = p_note,
    reviewed_by = v_admin,
    reviewed_at = now()
  where id = p_request_id;

  if not p_accept then
    return null;
  end if;

  insert into public.sentences (language, mode, text, is_meme, source_request_id, created_by)
  values (v_request.language, v_request.mode, v_final, coalesce(p_is_meme, false), p_request_id, v_admin)
  returning id into v_sentence_id;

  return v_sentence_id;
end;
$$;

create or replace function public.get_sentence_requests(
  p_status text default 'pending',
  p_limit integer default 100
)
returns table (
  id bigint,
  display_name text,
  language text,
  mode text,
  text text,
  status text,
  created_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select r.id, coalesce(nullif(p.display_name, ''), '익명'), r.language, r.mode, r.text, r.status, r.created_at
  from public.sentence_requests r
  join public.profiles p on p.id = r.profile_id
  where public.is_admin()
    and (p_status is null or r.status = p_status)
  order by r.created_at desc
  limit least(greatest(coalesce(p_limit, 100), 1), 500)
$$;

-- ---------------------------------------------------------------------------
-- RLS / 권한
-- ---------------------------------------------------------------------------

alter table public.sentences enable row level security;
alter table public.sentence_requests enable row level security;
alter table public.event_prizes enable row level security;

-- 문장은 누구나 읽는다. 쓰기는 관리자만.
drop policy if exists "sentences_read" on public.sentences;
create policy "sentences_read" on public.sentences
for select to anon, authenticated using (enabled or public.is_admin());

drop policy if exists "sentences_admin_write" on public.sentences;
create policy "sentences_admin_write" on public.sentences
for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- 요청은 본인 것만 본다. 관리자는 전부.
drop policy if exists "sentence_requests_own" on public.sentence_requests;
create policy "sentence_requests_own" on public.sentence_requests
for select to authenticated
using (profile_id = public.current_profile_id() or public.is_admin());

drop policy if exists "sentence_requests_admin_write" on public.sentence_requests;
create policy "sentence_requests_admin_write" on public.sentence_requests
for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- 경품은 누구나 읽고 관리자만 고친다.
drop policy if exists "event_prizes_read" on public.event_prizes;
create policy "event_prizes_read" on public.event_prizes
for select to anon, authenticated using (enabled or public.is_admin());

drop policy if exists "event_prizes_admin_write" on public.event_prizes;
create policy "event_prizes_admin_write" on public.event_prizes
for all to authenticated using (public.is_admin()) with check (public.is_admin());

revoke all on public.sentences from anon, authenticated;
revoke all on public.sentence_requests from anon, authenticated;
revoke all on public.event_prizes from anon, authenticated;

grant select on public.sentences to anon, authenticated;
grant select on public.event_prizes to anon, authenticated;
grant select on public.sentence_requests to authenticated;
-- 관리자 화면의 직접 편집(추가/수정/삭제)은 RLS가 is_admin()으로 막는다.
grant insert, update, delete on public.sentences to authenticated;
grant insert, update, delete on public.event_prizes to authenticated;
grant update, delete on public.sentence_requests to authenticated;
grant usage on all sequences in schema public to authenticated;

grant execute on function public.update_my_display_name(text) to authenticated;
grant execute on function public.submit_sentence_request(text, text, text) to authenticated;
grant execute on function public.review_sentence_request(bigint, boolean, text, text, boolean) to authenticated;
grant execute on function public.get_sentence_requests(text, integer) to authenticated;

notify pgrst, 'reload schema';
