create table if not exists public.prize_draws (
  id bigint generated by default as identity primary key,
  month_id text not null check (month_id ~ '^[0-9]{6}$'),
  drawn_at timestamptz not null default now(),
  -- 추첨 시점의 후보 규모. 나중에 확률을 설명할 수 있어야 한다.
  candidate_count integer not null,
  total_tickets integer not null,
  -- 재추첨도 같은 달에 여러 번 일어난다. 몇 번째 실행인지.
  round integer not null default 1,
  note text,
  unique (month_id, round)
);

comment on table public.prize_draws is
  '월별 추첨 실행 기록. 경품 분쟁에 답하기 위한 근거이므로 지우지 않는다.';

-- ---------------------------------------------------------------------------
-- 당첨자
-- ---------------------------------------------------------------------------
--
-- 상태 기계
--   pending   추첨됨. 주소 입력 대기 (3일)
--   confirmed 주소를 받았다
--   expired   3일이 지나 무효. 재추첨 대상
--   voided    관리자가 취소 (부정행위 등)

create table if not exists public.prize_winners (
  id bigint generated by default as identity primary key,
  draw_id bigint not null references public.prize_draws(id) on delete cascade,
  month_id text not null check (month_id ~ '^[0-9]{6}$'),
  profile_id uuid not null references public.profiles(id) on delete cascade,
  prize_id bigint references public.event_prizes(id) on delete set null,
  -- 경품이 나중에 지워져도 무엇에 당첨됐는지는 남아야 한다.
  prize_name text not null,
  prize_sponsor text,
  -- 추첨 당시의 등수·응모권·전체 응모권. 확률을 그대로 재현할 수 있다.
  score_at_draw integer not null,
  rank_at_draw integer not null,
  tickets_at_draw integer not null,
  total_tickets_at_draw integer not null,
  status text not null default 'pending'
    check (status in ('pending', 'confirmed', 'expired', 'voided')),
  -- 주소 입력 마감. 지나면 expire_stale_winners가 정리한다.
  respond_by timestamptz not null,
  notified_at timestamptz,
  responded_at timestamptz,
  /* 주소를 어디로 받았는지.
     당첨자가 사이트를 안 쓰고 메일로 회신하는 경우가 있어서, 관리자가 손으로
     "받았음"을 표시할 수 있어야 한다. 그때는 'email'이 된다. */
  response_channel text check (response_channel in ('site', 'email', 'manual')),
  response_note text,
  voided_reason text,
  created_at timestamptz not null default now(),
  -- 같은 달에 같은 사람이 두 경품을 받지 않게 한다.
  unique (month_id, profile_id)
);

create index if not exists prize_winners_pending_idx
  on public.prize_winners (respond_by) where status = 'pending';
create index if not exists prize_winners_profile_idx
  on public.prize_winners (profile_id, created_at desc);
-- 메일을 아직 못 보낸 당첨자를 찾는 경로.
create index if not exists prize_winners_unnotified_idx
  on public.prize_winners (created_at) where notified_at is null and status = 'pending';

