/** 부정행위 등으로 당첨을 취소한다. 빈 자리는 다음 재추첨에서 채워진다. */
create or replace function public.void_prize_winner(p_winner_id bigint, p_reason text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'Admin only';
  end if;
  if char_length(btrim(coalesce(p_reason, ''))) < 2 then
    raise exception '취소 사유를 남겨야 합니다';
  end if;

  update public.prize_winners
  set status = 'voided', voided_reason = btrim(p_reason)
  where id = p_winner_id and status in ('pending', 'confirmed');

  if not found then
    raise exception '취소할 수 있는 당첨이 아닙니다';
  end if;
end;
$$;

/** 배송이 끝난 주소를 파기한다. 개인정보를 필요 이상으로 들고 있지 않는다. */
create or replace function public.purge_delivered_addresses(p_days integer default 90)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_deleted integer;
begin
  delete from public.winner_addresses a
  using public.prize_winners w
  where w.id = a.winner_id
    and w.status = 'confirmed'
    and w.responded_at < now() - make_interval(days => greatest(coalesce(p_days, 90), 7));

  get diagnostics v_deleted = row_count;
  return v_deleted;
end;
$$;

