create or replace function public.get_prize_winners(
  p_month_id text default null,
  p_limit integer default 100
)
returns table (
  winner_id bigint,
  month_id text,
  display_name text,
  email text,
  prize_name text,
  score_at_draw integer,
  rank_at_draw integer,
  tickets_at_draw integer,
  win_odds numeric,
  status text,
  respond_by timestamptz,
  notified_at timestamptz,
  response_channel text,
  response_note text,
  has_address boolean,
  created_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select
    w.id,
    w.month_id,
    coalesce(nullif(p.display_name, ''), '익명'),
    p.email::text,
    w.prize_name,
    w.score_at_draw,
    w.rank_at_draw,
    w.tickets_at_draw,
    -- 추첨 당시 이 사람의 응모권 비중. "왜 당첨됐나"에 답하는 값이다.
    case when w.total_tickets_at_draw > 0
      then round(w.tickets_at_draw::numeric * 100 / w.total_tickets_at_draw, 2)
      else 0 end,
    w.status,
    w.respond_by,
    w.notified_at,
    w.response_channel,
    w.response_note,
    exists (select 1 from public.winner_addresses a where a.winner_id = w.id),
    w.created_at
  from public.prize_winners w
  join public.profiles p on p.id = w.profile_id
  where public.is_admin()
    and (p_month_id is null or w.month_id = p_month_id)
  order by w.created_at desc
  limit least(greatest(coalesce(p_limit, 100), 1), 500)
$$;

