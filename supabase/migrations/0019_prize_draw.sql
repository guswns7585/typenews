/**
 * 등수별 응모권을 나눠 갖고 그중에서 당첨자를 뽑는다.
 *
 * - 등수는 **그 달 최종 순위**로 한 번 매긴다. 재추첨에서도 다시 매기지 않는다.
 *   앞사람이 당첨됐다고 내 등수가 올라가면 "1등 8장"의 의미가 흔들린다.
 * - 뽑기는 지수 경주(exponential race): -ln(1-random())/응모권 이 가장 작은 쪽.
 *   응모권 수에 정확히 비례하는 확률이고, 중복 없이 여러 명 뽑을 때도 유지된다.
 * - 그 달에 한 번이라도 뽑힌 사람(만료·취소 포함)은 후보에서 빠진다.
 * - 51등 밖과 점수 0은 후보가 아니다.
 * - 같은 달에 두 번 불러도 이미 채워진 경품은 다시 뽑지 않는다.
 */
create or replace function public.run_monthly_draw(
  p_month_id text,
  p_note text default null
)
returns table (
  winner_id bigint,
  profile_id uuid,
  prize_name text,
  rank_at_draw integer,
  tickets_at_draw integer
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_round integer;
  v_draw_id bigint;
  v_candidates integer;
  v_total integer;
  v_prize record;
  v_pick record;
  v_winner_id bigint;
  v_deadline timestamptz;
begin
  /* 회신 기한: 추첨일 + 2일의 23:50 (KST).
     1일 00:00 추첨 → 3일 23:50, 4일 재추첨 → 6일 23:50.
     KST로 바꿔 날짜를 자른 뒤 다시 timestamptz로 되돌린다. */
  v_deadline := (
    date_trunc('day', now() at time zone 'Asia/Seoul')
    + interval '2 days' + interval '23 hours 50 minutes'
  ) at time zone 'Asia/Seoul';
  if p_month_id !~ '^[0-9]{6}$' then
    raise exception '잘못된 month_id입니다';
  end if;

  -- 아직 주인이 없는 경품만 대상이다. 이미 pending/confirmed면 건너뛴다.
  if not exists (
    select 1 from public.event_prizes p
    where p.enabled
      and not exists (
        select 1 from public.prize_winners w
        where w.month_id = p_month_id
          and w.prize_id = p.id
          and w.status in ('pending', 'confirmed')
      )
  ) then
    return;
  end if;

  select coalesce(max(d.round), 0) + 1 into v_round
  from public.prize_draws d where d.month_id = p_month_id;

  /* 그 달의 후보 풀을 임시 테이블에 고정한다.
     등수를 한 번만 매기기 위해서다. 경품마다 다시 계산하면 앞서 뽑힌 사람이
     빠지면서 등수가 밀려 올라가 응모권 수가 달라진다.

     ⚠️ 상태를 가리지 않고 그 달에 한 번이라도 뽑힌 사람은 전부 뺀다.
     expired(무응답)와 voided(취소)도 마찬가지다. 안 그러면 재추첨에서 다시 뽑혀
     unique (month_id, profile_id)에 걸려 추첨 전체가 실패한다.
     기한을 넘긴 사람에게 다시 기회를 주지 않는다는 정책과도 맞는다. */
  create temporary table if not exists draw_pool (
    profile_id uuid primary key,
    score integer not null,
    rank integer not null,
    tickets integer not null
  ) on commit drop;
  delete from draw_pool;

  insert into draw_pool (profile_id, score, rank, tickets)
  select r.profile_id, r.score, r.rank,
    case
      when r.rank = 1 then 8
      when r.rank = 2 then 5
      when r.rank = 3 then 3
      when r.rank between 4 and 10 then 2
      when r.rank between 11 and 50 then 1
      else 0
    end
  from (
    select
      ms.profile_id,
      ms.score,
      /* 랭킹 화면과 같은 순서여야 한다(get_monthly_ranking).
         마지막 profile_id는 동점·동시각일 때 순서를 고정하기 위한 것이다. */
      row_number() over (
        order by ms.score desc, ms.updated_at desc, ms.profile_id
      )::integer as rank
    from public.monthly_stats ms
    where ms.month_id = p_month_id and ms.score > 0
  ) r
  where not exists (
    select 1 from public.prize_winners w
    where w.month_id = p_month_id and w.profile_id = r.profile_id
  );

  delete from draw_pool where tickets = 0;

  select count(*)::integer, coalesce(sum(tickets), 0)::integer
  into v_candidates, v_total
  from draw_pool;

  if v_candidates = 0 then
    raise exception '추첨할 후보가 없습니다 (month_id=%)', p_month_id;
  end if;

  insert into public.prize_draws (month_id, candidate_count, total_tickets, round, note)
  values (p_month_id, v_candidates, v_total, v_round, p_note)
  returning id into v_draw_id;

  for v_prize in
    select p.id, p.name, p.sponsor
    from public.event_prizes p
    where p.enabled
      and not exists (
        select 1 from public.prize_winners w
        where w.month_id = p_month_id
          and w.prize_id = p.id
          and w.status in ('pending', 'confirmed')
      )
    order by p.sort_order, p.id
  loop
    /* 경품 하나마다 응모권 수에 비례해 한 명씩 뽑는다.
       random()은 [0,1)이라 0이 나올 수 있고 ln(0)은 오류다. 1-random()을 쓰면
       (0,1]이 되어 안전하다.
       뽑힌 사람은 풀에서 지워 다음 경품에 다시 나오지 않게 한다. */
    v_pick := null;
    select d.profile_id, d.score, d.rank, d.tickets
    into v_pick
    from draw_pool d
    order by -ln(1 - random()) / d.tickets
    limit 1;

    -- 후보가 경품 수보다 적으면 남은 경품은 다음 기회로 넘긴다.
    exit when v_pick is null;
    delete from draw_pool where draw_pool.profile_id = v_pick.profile_id;

    insert into public.prize_winners (
      draw_id, month_id, profile_id, prize_id, prize_name, prize_sponsor,
      score_at_draw, rank_at_draw, tickets_at_draw, total_tickets_at_draw, respond_by
    )
    values (
      v_draw_id, p_month_id, v_pick.profile_id, v_prize.id, v_prize.name, v_prize.sponsor,
      v_pick.score, v_pick.rank, v_pick.tickets, v_total, v_deadline
    )
    returning id into v_winner_id;

    /* OUT 파라미터에 직접 RETURNING 하지 않는다. profile_id·prize_name 등은
       컬럼 이름과 같아서 RETURNING 목록이 모호해진다. */
    winner_id := v_winner_id;
    profile_id := v_pick.profile_id;
    prize_name := v_prize.name;
    rank_at_draw := v_pick.rank;
    tickets_at_draw := v_pick.tickets;
    return next;
  end loop;
end;
$$;

/**
 * 3일이 지나도 주소를 안 넣은 당첨을 무효 처리하고 재추첨한다.
 * pg_cron으로 하루 한 번 돈다.
 */
create or replace function public.expire_stale_winners()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_expired integer;
  v_month text;
  v_months text[];
begin
  /* ⚠️ 이번 실행에서 만료된 달만 모은다.
     예전에는 status='expired'인 행 전체에서 달을 뽑았는데, 그러면 지난달·지지난달이
     매일 다시 추첨 대상이 됐다. 게다가 event_prizes는 "지금" 걸린 경품이라
     지난달을 현재 경품으로 다시 뽑는 것은 애초에 틀린 동작이다. */
  with expired as (
    update public.prize_winners
    set status = 'expired'
    where status = 'pending' and respond_by < now()
    returning month_id
  )
  select count(*), array_agg(distinct month_id) into v_expired, v_months from expired;

  if coalesce(v_expired, 0) = 0 then
    return 0;
  end if;

  -- 빈 자리가 생긴 달마다 재추첨한다.
  foreach v_month in array coalesce(v_months, array[]::text[])
  loop
    begin
      perform public.run_monthly_draw(v_month, '무응답 재추첨');
    exception when others then
      -- 후보가 없으면 넘어간다. 한 달이 실패해도 나머지는 처리해야 한다.
      raise notice '재추첨 실패 (month_id=%): %', v_month, sqlerrm;
    end;
  end loop;

  return v_expired;
end;
$$;

