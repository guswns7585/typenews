-- 월간 경품 추첨 자동화의 데이터 계층.
--
-- 정해진 규칙
--   - 랭킹 마감: 말일 23:59:59 (KST)
--   - 추첨: 다음 달 1일 00:00 (KST)
--   - 주소 회신 기한: 추첨일 + 2일의 23:50 (KST)
--       1회차 1일 00:00 추첨 → 3일 23:50 마감
--       2회차 4일 00:00 재추첨 → 6일 23:50 마감
--   - 등수에 따라 응모권을 나눠 갖고 그중에서 뽑는다 (마블 룰렛과 같은 방식)
--
-- 응모권 배분 — 기존 운영 방식을 그대로 옮긴 것이다.
--
--   | 등수    | 응모권 | 1명 뽑을 때 확률 |
--   |---------|--------|------------------|
--   | 1등     | 8장    | 11.43%           |
--   | 2등     | 5장    | 7.14%            |
--   | 3등     | 3장    | 4.29%            |
--   | 4~10등  | 각 2장 | 각 2.86%         |
--   | 11~50등 | 각 1장 | 각 1.43%         |
--   | 51등~   | 없음   | 후보 아님        |
--
--   총 8 + 5 + 3 + (7x2) + (40x1) = 70장.
--
-- ⚠️ 점수 자체가 아니라 **등수**가 확률을 정한다. 점수가 두 배라고 확률이 두 배가
--    되지는 않는다. 등수는 그 달 최종 순위로 한 번 정하고, 재추첨에서도 바뀌지
--    않는다 — 다른 사람이 당첨됐다고 내 등수가 올라가지는 않는다.
--
-- ⚠️ 점수 적립 경로는 건드리지 않는다. 여기서는 monthly_stats를 읽기만 한다.
--
-- 이 마이그레이션은 DB 계층만 만든다. 메일 발송과 스케줄러는 별도다.
-- 메일: Supabase는 인증 메일만 보낸다. 외부 HTTP API(Resend 등)가 필요하다.
-- 스케줄: pg_cron. 아래 맨 아래에 등록 예시를 적어뒀다.

