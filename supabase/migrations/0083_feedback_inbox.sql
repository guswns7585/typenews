begin;

create table if not exists public.feedback_submissions (
  id bigint generated by default as identity primary key,
  profile_id uuid references public.profiles(id) on delete set null,
  category text not null check (category in ('bug', 'feature', 'content', 'other')),
  title text not null check (char_length(btrim(title)) between 1 and 120),
  body text not null check (char_length(btrim(body)) between 1 and 3000),
  page_path text not null default '' check (char_length(page_path) <= 500),
  user_agent text not null default '' check (char_length(user_agent) <= 500),
  contact_email citext check (contact_email is null or char_length(contact_email::text) <= 254),
  request_fingerprint text not null check (char_length(request_fingerprint) = 64),
  status text not null default 'received' check (status in ('received', 'reviewing', 'planned', 'completed', 'declined')),
  admin_reply text not null default '' check (char_length(admin_reply) <= 3000),
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists feedback_submissions_created_idx
on public.feedback_submissions (created_at desc, id desc);
create index if not exists feedback_submissions_status_created_idx
on public.feedback_submissions (status, created_at desc);
create index if not exists feedback_submissions_fingerprint_created_idx
on public.feedback_submissions (request_fingerprint, created_at desc);

drop trigger if exists feedback_submissions_touch_updated_at on public.feedback_submissions;
create trigger feedback_submissions_touch_updated_at
before update on public.feedback_submissions
for each row execute function public.touch_updated_at();

alter table public.feedback_submissions enable row level security;
revoke all on table public.feedback_submissions from public, anon, authenticated;

create or replace function public.get_admin_feedback(
  p_status text default null,
  p_limit integer default 200
)
returns table (
  feedback_id bigint,
  profile_id uuid,
  display_name text,
  account_email text,
  category text,
  title text,
  body text,
  page_path text,
  user_agent text,
  contact_email text,
  status text,
  admin_reply text,
  created_at timestamptz,
  updated_at timestamptz
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then raise exception 'Admin only'; end if;
  if p_status is not null and p_status not in ('received', 'reviewing', 'planned', 'completed', 'declined') then
    raise exception 'Invalid feedback status';
  end if;

  return query
  select
    f.id,
    f.profile_id,
    coalesce(nullif(p.display_name, ''), '비로그인'),
    p.email::text,
    f.category,
    f.title,
    f.body,
    f.page_path,
    f.user_agent,
    f.contact_email::text,
    f.status,
    f.admin_reply,
    f.created_at,
    f.updated_at
  from public.feedback_submissions f
  left join public.profiles p on p.id = f.profile_id
  where p_status is null or f.status = p_status
  order by
    case f.status when 'received' then 0 when 'reviewing' then 1 when 'planned' then 2 else 3 end,
    f.created_at desc,
    f.id desc
  limit least(greatest(coalesce(p_limit, 200), 1), 500);
end;
$$;

create or replace function public.admin_update_feedback(
  p_feedback_id bigint,
  p_status text,
  p_admin_reply text default ''
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_reply text := btrim(coalesce(p_admin_reply, ''));
begin
  if not public.is_admin() then raise exception 'Admin only'; end if;
  if p_status not in ('received', 'reviewing', 'planned', 'completed', 'declined') then
    raise exception 'Invalid feedback status';
  end if;
  if char_length(v_reply) > 3000 then raise exception '답변은 3,000자 이하여야 합니다'; end if;

  update public.feedback_submissions
  set status = p_status,
      admin_reply = v_reply,
      reviewed_by = public.current_profile_id(),
      reviewed_at = now()
  where id = p_feedback_id;
  if not found then raise exception 'Feedback not found'; end if;
end;
$$;

revoke all on function public.get_admin_feedback(text, integer) from public, anon;
revoke all on function public.admin_update_feedback(bigint, text, text) from public, anon;
grant execute on function public.get_admin_feedback(text, integer) to authenticated;
grant execute on function public.admin_update_feedback(bigint, text, text) to authenticated;

notify pgrst, 'reload schema';

commit;
