-- Ensure the per-sentence typing result table is available to PostgREST.
-- Safe to run after 0001; existing rows and objects are preserved.

create table if not exists public.typing_results (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  month_id text not null check (month_id ~ '^[0-9]{6}$'),
  mode text not null check (mode in ('short', 'long', 'word', 'news')),
  accuracy integer not null check (accuracy between 0 and 100),
  cpm integer not null check (cpm >= 0 and cpm <= 5000),
  counted_for_ranking boolean not null default true,
  created_at timestamptz not null default now()
);

create index if not exists typing_results_profile_created_idx
on public.typing_results (profile_id, created_at desc);

alter table public.typing_results enable row level security;

drop policy if exists "typing_results_select_own" on public.typing_results;
create policy "typing_results_select_own"
on public.typing_results for select
to authenticated
using (profile_id = public.current_profile_id());

revoke all on public.typing_results from anon;
grant select on public.typing_results to authenticated;

notify pgrst, 'reload schema';
